namespace VotingSystem.Models;

// Модель представления для формы голосования за кандидата
// Используется для передачи данных из формы голосования в контроллер
public class VoteViewModel
{
    // Идентификатор кандидата, за которого пользователь голосует
    public int CandidateId { get; set; }
    // Необязательный комментарий к голосу (может быть null)
    public string? Comment { get; set; }
}
